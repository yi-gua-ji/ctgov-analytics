import duckdb
con = duckdb.connect(r"D:\projects\ctgov-analytics\data\ctgov.duckdb", read_only=True)
def q(s): return con.execute(s).fetchall()
print("total trials:", q("SELECT COUNT(*) FROM stg_studies")[0][0])
print("ymin/ymax:", q("SELECT MIN(start_year), MAX(start_year) FROM v_trials")[0])
print("years >=2026:", q("SELECT start_year, COUNT(*) FROM v_trials WHERE start_year >= 2026 GROUP BY 1 ORDER BY 1"))
print("years 1990-2005:", q("SELECT start_year, COUNT(*) FROM v_trials WHERE start_year BETWEEN 1990 AND 2005 GROUP BY 1 ORDER BY 1"))
print("completed:", q("SELECT SUM(is_completed), COUNT(*) FROM v_trials")[0])
print("stopped:", q("SELECT SUM(is_stopped) FROM v_trials")[0])
print("sglt2:", q("SELECT SUM(is_sglt2) FROM v_trials")[0])
print("results:", q("SELECT SUM(CASE WHEN has_results THEN 1 ELSE 0 END) FROM v_trials")[0])
print("median enrollment:", q("SELECT MEDIAN(enrollment_count) FROM v_trials")[0])
print("runs:", q("SELECT run_id, queries, status, n_fetched, n_upserted FROM etl_runs"))
print("phase null pct:", q("SELECT ROUND(AVG(CASE WHEN phase_category IS NULL THEN 1.0 ELSE 0 END),4) FROM v_trials")[0])